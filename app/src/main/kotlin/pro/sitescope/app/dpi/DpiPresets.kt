package pro.sitescope.app.dpi

/**
 * Готовые профили: проверенные строки ключей byedpi с понятным названием.
 * Профиль нужен, чтобы не разбираться в ключах: выберите, запустите, проверьте. Если не помогло — запустите «Подобрать и включить».
 */
object DpiPresets {
    class Preset(val id: String, val title: String, val hint: String, val line: String)

    val all = listOf(
        Preset("soft", "Мягкий", "Минимум вмешательства: режет первый пакет TLS. Меньше всего ломает сайты, подходит как первая попытка.", DpiConfig.SAFE_LINE),
        Preset("universal", "Универсальный", "Разрез TLS-записи + разделение и обратный порядок. Самый частый рабочий вариант против DPI провайдеров.", "-r1+s -s1+s -d3+s"),
        Preset("fake", "Поддельные пакеты", "Отправляет «фальшивый» ClientHello, который не доходит до сервера, но сбивает DPI. Нужен, если простое разделение не помогает.", "-f-1 -t8 -n {sni} -Qr -s1+s"),
        Preset("chain", "Цепочка разрезов", "Дробит запрос на много кусочков. Помогает на строгих DPI, но может чуть снижать скорость.", "-d1 -s1+s -d3+s -s6+s -d9+s -s12+s -d15+s -s20+s -d25+s -s30+s -a1"),
        Preset("auto", "Автогруппы", "Движок сам включает нужные приёмы, когда замечает блокировку (по признакам ответа).", "-An -Kt,h -o1 -Ar -f-1 -t6 -At -d1+s -r1+s -As -s1+s"),
        Preset("heavy", "Максимальный", "Комбинация всех приёмов. Самый тяжёлый вариант — используйте, если всё остальное не открывает сайт.", "-n {sni} -Qr -f-204 -s1:5+sm -a1 -As -d1 -s3+s -s5+s -q7 -a1 -As -o2 -f-43 -a1 -As -r5 -Mh -s1:5+s -s3:7+sm -a1"),
    )

    fun byLine(line: String): Preset? {
        val key = line.trim()
        return all.firstOrNull { it.line == key }
    }

    /** Название для показа: профиль, если строка совпала, иначе «Своя строка». */
    fun titleOf(line: String): String = byLine(line)?.title ?: "Своя строка"
}
